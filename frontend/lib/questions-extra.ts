function gamma(
  id: string,
  difficulty: Question['difficulty'],
  transcript: string,
  flags: FlagReason[],
  explanation: string,
  tags: string[],
): Question {
  return {
    id,
    type: 'gamma',
    difficulty,
    category: 'transcript',
    operationContext: 'Screen this text conversation before it is used. Pass it, or flag every problem.',
    prompt: 'Review the transcript below for clearance.',
    transcript,
    correctAnswer: { decision: flags.length ? 'FLAGGED' : 'CLEAR', flags },
    explanation: `Debrief: ${explanation}`,
    xpValue: 50,
    tags: ['transcript', ...tags],
  }
}

