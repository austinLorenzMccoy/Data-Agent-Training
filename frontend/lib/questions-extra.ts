// ─── Compare AI media ───────────────────────────────────────────────────────

function iota(
  id: string,
  difficulty: Question['difficulty'],
  category: string,
  axis: string,
  promptText: string,
  question: string,
  a: string,
  b: string,
  correct: 'A' | 'B',
  explanation: string,
  rubric: string,
  tags: string[],
): Question {
  return {
    id,
    type: 'iota',
    difficulty,
    category,
    operationContext: `Two generations from the same prompt. Judge only the ${axis} axis. Prompt: "${promptText}"`,
    prompt: question,
    responseA: `Output A: ${a}`,
    responseB: `Output B: ${b}`,
    correctAnswer: correct,
    explanation: `Debrief: ${explanation}`,
    rubric,
    xpValue: 60,
    tags: [...tags, 'media-comparison'],
  }
}

