// ─── Pick the best reply ────────────────────────────────────────────────────

function delta(
  id: string,
  difficulty: Question['difficulty'],
  transcript: string,
  replyAs: string,
  responses: [string, string, string, string],
  correct: 0 | 1 | 2 | 3,
  explanation: string,
): Question {
  const lines = transcript.split('\n')
  const last = lines[lines.length - 1]
  const [speaker, ...rest] = last.split(': ')
  return {
    id,
    type: 'delta',
    difficulty,
    category: 'selection',
    operationContext: 'This conversation passed review. Pick the reply the other person would actually send.',
    transcript,
    prompt: `${speaker}: "${rest.join(': ')}" — reply as ${replyAs}.`,
    responses,
    correctAnswer: correct,
    explanation: `Debrief: ${explanation}`,
    xpValue: 50,
    tags: ['selection'],
  }
}

