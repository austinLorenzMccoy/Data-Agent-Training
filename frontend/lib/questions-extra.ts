function seg(speaker: number, gender: ThetaSegment['gender'], start_ms: number, end_ms: number, transcript: string): ThetaSegment {
  return { speaker, gender, start_ms, end_ms, transcript, tags: [] }
}

function theta(
  id: string,
  difficulty: Question['difficulty'],
  clip: string,
  duration_seconds: number,
  segments: ThetaSegment[],
  explanation: string,
): Question {
  const url = `/audio/${clip}.wav`
  return {
    id,
    type: 'theta',
    difficulty,
    category: 'transcription',
    operationContext:
      'Segment the clip, number speakers in the order they first speak, type exactly what is said, and set the audio-quality flags.',
    prompt: '',
    correctAnswer: {},
    explanation: `Debrief: ${explanation}`,
    xpValue: 75,
    tags: ['transcription'],
    audioAssetUrl: url,
    payload: {
      duration_seconds,
      audio_asset_url: url,
      reference_audio_quality_flags: ['synthesized_or_recorded'],
      reference_segments: segments,
    },
  }
}

